// Generates src/theme/frost-auto.css: dark "frost" overrides for every hard-coded light/earthy colour in the theme CSS.
// Each rule is re-emitted under `html.frost` (higher specificity), with colours remapped by role. Yeti art is excluded (frost.css styles it by hand).
import fs from "node:fs"; import path from "node:path"; import postcss from "postcss";
const dir = "src/theme";
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".css") && !f.startsWith("frost") && f !== "fonts.css" && f !== "space-yeti.css");
const SKIP = /\b(rb-(shell|torso|chest|ear|face|eye|hand|arm|mouth|alert)|yt-|space-yeti|my-|wb-coins|globe|g-body|g-atmo|land-|wn-orb|district)/;
const clamp = (x, a = 0, b = 1) => Math.min(b, Math.max(a, x));
function parse(c) {
  let m;
  if ((m = c.match(/^#([0-9a-f]{3,8})$/i))) { let h = m[1]; if (h.length <= 4) h = [...h].map((x) => x + x).join("");
    const n = (i) => parseInt(h.slice(i, i + 2), 16); return [n(0), n(2), n(4), h.length === 8 ? n(6) / 255 : 1]; }
  if ((m = c.match(/^rgba?\(([^)]+)\)$/i))) { const p = m[1].split(/[\s,/]+/).filter(Boolean).map(Number); return [p[0], p[1], p[2], p[3] ?? 1]; }
  return null;
}
function hsl([r, g, b]) { r /= 255; g /= 255; b /= 255; const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2; let h = 0, s = 0;
  if (mx !== mn) { const d = mx - mn; s = l > 0.5 ? d / (2 - mx - mn) : d / (mx + mn); h = mx === r ? (g - b) / d + (g < b ? 6 : 0) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4; h *= 60; } return [h, s, l]; }
const out = (h, s, l, a) => `hsla(${h.toFixed(0)}, ${(s * 100).toFixed(0)}%, ${(l * 100).toFixed(1)}%, ${+a.toFixed(3)})`;
function map(c, role) {
  const p = parse(c); if (!p) return c; const [h, s, l] = hsl(p); const a = p[3]; const sat = s > 0.25 && l > 0.15 && l < 0.85;
  if (role === "text") { if (l > 0.7 && !sat) return out(214, 0.35, Math.max(l, 0.9), a); return sat ? out(205, 0.6, 0.82, a) : out(216, 0.3, clamp(0.97 - l * 0.35, 0.8, 0.96), a); }
  if (role === "line") return sat ? out(208, 0.45, 0.72, clamp(a, 0, 0.6)) : out(214, 0.3, 0.72, clamp(a * (l > 0.5 ? 0.9 : 1.3), 0.08, 0.55));
  if (role === "shadow") return out(226, 0.6, 0.03, clamp(a * 1.2, 0, 0.8));
  // surface
  if (l > 0.55 && !sat) return out(222, 0.42, 0.09 + (1 - l) * 0.35, a < 1 ? clamp(a * 0.95, 0, 0.92) : 0.86);
  if (sat) return out(210, 0.5, clamp(l * 0.75, 0.25, 0.62), clamp(a, 0, 1));
  return out(222, 0.45, clamp(l, 0.05, 0.22), a);
}
const COLOR = /#[0-9a-f]{3,8}\b|rgba?\([^)]*\)/gi;
const roleOf = (p) => /^(color|-webkit-text-fill-color|caret-color)$/.test(p) ? "text" : /^(border|outline|stroke|text-decoration|column-rule)/.test(p) ? "line" : /shadow/.test(p) ? "shadow" : /^(background|fill|stop-color)/.test(p) ? "surface" : null;
let css = "/* AUTO-GENERATED by scripts/gen-frost.mjs — do not edit by hand. Frost (dark navy) remap of hard-coded theme colours. */\n";
let n = 0;
for (const f of files) {
  const root = postcss.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  root.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && /keyframes/.test(rule.parent.name)) return;
    if (rule.selector.includes(":root") || SKIP.test(rule.selector)) return;
    const decls = [];
    const clipText = rule.nodes.some((d) => d.type === "decl" && /background-clip$/.test(d.prop) && /text/.test(d.value));
    rule.each((d) => { if (d.type !== "decl") return; const role = clipText && /^background/.test(d.prop) ? "text" : roleOf(d.prop); if (!role || /url\(/.test(d.value) || /var\(/.test(d.value) && !COLOR.test(d.value)) return; COLOR.lastIndex = 0;
      if (!COLOR.test(d.value)) return; COLOR.lastIndex = 0; let v = d.value.replace(COLOR, (c) => map(c, role)); if (/white|#fff\b/i.test(v) && role === "text") v = v.replace(/\bwhite\b/g, "#f2f6fc");
      decls.push(`${d.prop}: ${v}${d.important ? " !important" : ""};`); });
    if (!decls.length) return;
    // keep gradient text working: a re-emitted `background` shorthand resets background-clip, so restate it
    rule.each((d) => { if (d.type === "decl" && /background-clip$/.test(d.prop)) decls.push(`${d.prop}: ${d.value}${d.important ? " !important" : ""};`); });
    const sel = rule.selector.split(",").map((s) => s.trim()).map((s) => /^(html|body)\b/.test(s) ? s.replace(/^html/, "html.frost").replace(/^body/, "html.frost body") : `html.frost ${s}`).join(", ");
    let block = `${sel} { ${decls.join(" ")} }`;
    let p = rule.parent; while (p && p.type === "atrule") { if (/media|supports/.test(p.name)) block = `@${p.name} ${p.params} { ${block} }`; p = p.parent; }
    css += block + "\n"; n++;
  });
}
fs.writeFileSync(path.join(dir, "frost-auto.css"), css);
console.log("frost-auto rules:", n, "from", files.length, "files");
