// Generates src/config/lp-curated.json: the hand-picked, issuer-verified asset list for native pools.
// Source: ../config/assets.mainnet.json (each issuer's stellar.toml, or the issuer's own docs, checked read-only).
// Only entries with verified === true are kept; matching is ALWAYS on code + issuer, never ticker alone.
import { readFileSync, writeFileSync } from "node:fs";
const src = JSON.parse(readFileSync(new URL("../../config/assets.mainnet.json", import.meta.url), "utf8"));
const keep = src.assets.filter((a) => a.verified).map((a) => ({
  code: a.code, issuer: a.issuer, category: a.category, peg: a.peg, name: a.name ?? a.org ?? a.code,
  homeDomain: a.homeDomain, verification: a.verification, verifiedVia: a.verifiedVia, logo: a.logo ?? null,
  authRequired: !!a.authRequired,
}));
const out = { _comment: "Generated by scripts/gen-lp-curated.mjs. Verified issuers only (code + issuer).", verifiedAt: src.generatedAt, mainnet: keep };
writeFileSync(new URL("../src/config/lp-curated.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
console.log("kept", keep.length, "of", src.assets.length);
